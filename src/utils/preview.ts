/**
 * 列表预览纯文本化
 * ------------------------------------------------------------------
 * 收藏/列表里的"摘要"只有一行、几十个字符，直接把 AI 原文截断会有两个真实问题：
 *
 *   1) 公式源码裸露：`若 $x>0$ 则……` 在预览里显示成带美元符号的源码，
 *      而且 `slice(0, 60)` 很可能把 `$...$` **从中间剪断**，只剩半截公式；
 *   2) Markdown 标记裸露：`## 标题`、`**重点**`、`| 列 | 列 |` 原样出现在预览里。
 *
 * 所以预览文案必须先**降级为纯文本**再截断：
 *   - 公式围符（`$` `$$` `\(` `\[`）去掉、保留内部内容（内容本身仍是可读的数学写法）
 *   - Markdown 标记去掉、链接保留文字、图片整段丢弃
 *   - 所有空白折叠成单个空格（预览是一行）
 *   - 截断时不允许留下半截反斜杠命令（`\fra` 这种）
 */

/** 把任意 AI 文本降级为单行纯文本预览，并按 maxLen 截断 */
export function toPlainPreview(raw: string | null | undefined, maxLen = 60): string {
  if (!raw) return '';
  let s = String(raw);

  // 代码块：整块丢弃（预览里没有意义，且可能很长）
  s = s.replace(/```[\s\S]*?```/g, ' ');
  // 行内代码：保留内容
  s = s.replace(/`([^`]*)`/g, '$1');

  // 块级公式围符 → 去围符保留内容（必须先处理 $$ 再处理 $）
  s = s.replace(/\$\$([\s\S]*?)\$\$/g, '$1').replace(/\\\[([\s\S]*?)\\\]/g, '$1');
  // 行内公式围符 → 去围符保留内容
  s = s.replace(/\$([^$\n]+)\$/g, '$1').replace(/\\\(([\s\S]*?)\\\)/g, '$1');

  // Markdown 标记
  s = s
    .replace(/!\[[^\]]*\]\([^)]*\)/g, ' ')   // 图片整段丢弃
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1') // 链接保留可见文字
    .replace(/^\s{0,3}#{1,6}\s+/gm, '')      // 标题
    .replace(/^\s{0,3}>\s?/gm, '')           // 引用
    .replace(/^\s{0,3}[-*+]\s+/gm, '')       // 无序列表
    .replace(/^\s{0,3}\d+\.\s+/gm, '')       // 有序列表
    .replace(/\*\*([^*]+)\*\*/g, '$1')
    .replace(/__([^_]+)__/g, '$1')
    .replace(/\*([^*]+)\*/g, '$1')
    .replace(/~~([^~]+)~~/g, '$1')
    .replace(/\|/g, ' ');                    // 表格竖线

  // 折叠空白（预览是一行）
  s = s.replace(/\s+/g, ' ').trim();

  if (s.length <= maxLen) return s;

  // 截断后不允许留下半截反斜杠命令 / 尾随反斜杠
  const cut = s.slice(0, maxLen).replace(/\\[a-zA-Z]*$/, '').replace(/\\+$/, '').trimEnd();
  return `${cut}…`;
}
